/* Attendance Register — service worker
   Bump CACHE_VERSION whenever index.html changes, otherwise installed copies
   keep serving the old page until the browser happens to revalidate. */

var CACHE_VERSION = 'bda-att-v3';
var SHELL = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/apple-touch-icon.png'
];

self.addEventListener('install', function (e) {
  e.waitUntil(
    caches.open(CACHE_VERSION)
      .then(function (c) { return c.addAll(SHELL); })
      .then(function () { return self.skipWaiting(); })
  );
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k !== CACHE_VERSION) return caches.delete(k);
      }));
    }).then(function () { return self.clients.claim(); })
  );
});

self.addEventListener('message', function (e) {
  if (e.data === 'skipWaiting') self.skipWaiting();
});

self.addEventListener('fetch', function (e) {
  var req = e.request;

  // Never touch anything that isn't a plain GET. All the Apps Script traffic is
  // POST, so it goes straight to the network and is never cached.
  if (req.method !== 'GET') return;

  var url = new URL(req.url);
  if (url.hostname.indexOf('script.google') > -1 ||
      url.hostname.indexOf('googleusercontent') > -1) return;

  // The page itself: network first, so a new deploy is picked up immediately,
  // with the cached copy as the offline fallback.
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req).then(function (res) {
        var copy = res.clone();
        caches.open(CACHE_VERSION).then(function (c) { c.put('./index.html', copy); });
        return res;
      }).catch(function () {
        return caches.match('./index.html').then(function (r) {
          return r || caches.match('./');
        });
      })
    );
    return;
  }

  // Fonts, the SheetJS bundle, icons: cache first, refresh quietly behind it.
  e.respondWith(
    caches.match(req).then(function (hit) {
      var live = fetch(req).then(function (res) {
        if (res && res.status === 200) {
          var copy = res.clone();
          caches.open(CACHE_VERSION).then(function (c) { c.put(req, copy); });
        }
        return res;
      }).catch(function () { return hit; });
      return hit || live;
    })
  );
});
